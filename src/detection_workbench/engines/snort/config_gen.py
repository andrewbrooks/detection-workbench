"""Generate snort.lua from typed options. Values pass through safety.lua; nothing is ever built
from free text, and nothing here sets a DAQ, inline mode, or any capture setting."""
from __future__ import annotations

from ...safety import lua

ALERT_FIELDS = ("timestamp seconds pkt_num proto pkt_gen pkt_len dir src_addr src_port dst_addr dst_port "
                "service rule gid sid rev msg class priority action b64_data")
FILTER_TYPES = ("suppress", "event_filter", "rate_filter")
_TRACK = {"by_src", "by_dst"}
_RATE_TRACK = {"by_src", "by_dst", "by_rule"}
_EVENT_TYPE = {"limit", "threshold", "both"}
_RATE_ACTIONS = {"alert", "block", "drop", "log", "pass", "reject"}


class TuningError(ValueError):
    pass


def _record(pairs: list[tuple[str, str]]) -> str:
    return "{ " + ", ".join(f"{k} = {v}" for k, v in pairs) + " }"


def render_filter(f: dict) -> tuple[str, str]:
    """Return (table_name, lua record) for one structured filter. Unknown keys are errors."""
    kind = f.get("kind")
    body = {k: v for k, v in f.items() if k != "kind"}

    def take(allowed: set[str]):
        extra = set(body) - allowed
        if extra:
            raise TuningError(f"unknown field(s) for {kind}: {sorted(extra)}")

    try:
        gid = lua.lua_int(body.get("gid", 1), 0, 8129)
        sid = lua.lua_int(body["sid"], 0, 2**32 - 1)
        if kind == "suppress":
            take({"gid", "sid", "track", "ip"})
            pairs = [("gid", gid), ("sid", sid)]
            if "track" in body or "ip" in body:
                pairs += [("track", lua.lua_enum(body["track"], _TRACK)), ("ip", lua.lua_net(body["ip"]))]
            return "suppress", _record(pairs)
        if kind == "event_filter":
            take({"gid", "sid", "type", "track", "count", "seconds", "ip"})
            pairs = [("gid", gid), ("sid", sid), ("type", lua.lua_enum(body["type"], _EVENT_TYPE)),
                     ("track", lua.lua_enum(body["track"], _TRACK)),
                     ("count", lua.lua_int(body["count"], -1, 2**31 - 1)),
                     ("seconds", lua.lua_int(body["seconds"], 0, 2**32 - 1))]
            if "ip" in body:
                pairs.append(("ip", lua.lua_net(body["ip"])))
            return "event_filter", _record(pairs)
        if kind == "rate_filter":
            take({"gid", "sid", "track", "count", "seconds", "new_action", "timeout", "apply_to"})
            pairs = [("gid", gid), ("sid", sid), ("track", lua.lua_enum(body["track"], _RATE_TRACK)),
                     ("count", lua.lua_int(body["count"], 0, 2**32 - 1)),
                     ("seconds", lua.lua_int(body["seconds"], 0, 2**32 - 1)),
                     ("new_action", lua.lua_enum(body["new_action"], _RATE_ACTIONS)),
                     ("timeout", lua.lua_int(body["timeout"], 0, 2**32 - 1))]
            if "apply_to" in body:
                pairs.append(("apply_to", lua.lua_net(body["apply_to"])))
            return "rate_filter", _record(pairs)
    except KeyError as e:
        raise TuningError(f"{kind} needs field {e.args[0]!r}") from None
    except lua.LuaValueError as e:
        raise TuningError(f"invalid {kind}: {e}") from None
    raise TuningError(f"kind must be one of {FILTER_TYPES}")


def generate_config(*, etc_dir: str, home_net: str | None = None, external_net: str | None = None,
                    alert_file: bool = True, alert_limit_mb: int | None = None, profile: bool = False,
                    flush_one_sided: bool = False, filters: list[dict] | None = None) -> str:
    """Return Lua source. `etc_dir` is the engine-side directory with snort_defaults.lua (a trusted
    path from config/discovery, still quoted through lua_str)."""
    try:
        home = lua.lua_net(home_net) if home_net else "'any'"
        ext = lua.lua_net(external_net) if external_net else ("'!$HOME_NET'" if home_net else "'any'")
        defaults = lua.lua_str(etc_dir.rstrip("/") + "/snort_defaults.lua")
    except lua.LuaValueError as e:
        raise TuningError(f"invalid network or path: {e}") from None
    tables: dict[str, list[str]] = {}
    for f in filters or []:
        name, rec = render_filter(f)
        tables.setdefault(name, []).append(rec)
    L = [
        "-- generated by detection-workbench; do not edit",
        f"HOME_NET = {home}", f"EXTERNAL_NET = {ext}", f"include {defaults}", "",
        "stream = { }", "stream_ip = { }", "stream_udp = { }",
        "stream_tcp = { }" if not flush_one_sided else
        "stream_tcp = { queue_limit = { asymmetric_ids_flush_threshold = 1 } }",
        "http_inspect = { }", "dns = { }", "ssl = { }", "ssh = { }", "wizard = default_wizard", "",
        "ips = { variables = default_variables, enable_builtin_rules = false }",
        f"alert_json = {{ file = {lua.lua_bool(alert_file)}, fields = {lua.lua_str(ALERT_FIELDS)}"
        + (f", limit = {lua.lua_int(alert_limit_mb, 1, 100_000)}" if alert_limit_mb else "") + " }",
    ]
    if profile:
        L.append("profiler = { rules = { show = true, count = 0, sort = 'total_time' } }")
    for name, recs in tables.items():
        L.append(f"{name} = {{ " + ", ".join(recs) + " }")
    return "\n".join(L) + "\n"
